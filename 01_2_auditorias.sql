CREATE TABLE auditoria_guardias (
   id_auditoria   NUMBER(12) GENERATED BY DEFAULT AS IDENTITY,
   fecha_hora     TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
   usuario_bd     VARCHAR2(100) NOT NULL,
   usuario_so     VARCHAR2(100),
   tabla_afectada VARCHAR2(50)  NOT NULL,
   operacion      VARCHAR2(10)  NOT NULL,
   clave_registro VARCHAR2(200) NOT NULL,
   detalle_cambio VARCHAR2(1000),
   CONSTRAINT pk_auditoria_guardias PRIMARY KEY (id_auditoria)
);

-- 1. Trigger de auditoria sobre DESEMPENA
CREATE OR REPLACE TRIGGER trg_aud_desempena
AFTER INSERT OR UPDATE OR DELETE ON desempena
FOR EACH ROW
DECLARE
   v_op      VARCHAR2(10);
   v_clave   VARCHAR2(200);
   v_detalle VARCHAR2(1000);
BEGIN
   IF INSERTING THEN
      v_op      := 'INSERT';
      v_clave   := 'Mat:' || :NEW.matricula_medico || ' | Esp:' || :NEW.nombre_especialidad || ' | Guardia:' || :NEW.id_guardia;
      v_detalle := 'Alta de asignacion de guardia.';
   ELSIF UPDATING THEN
      v_op      := 'UPDATE';
      v_clave   := 'Mat:' || :OLD.matricula_medico || ' | Esp:' || :OLD.nombre_especialidad || ' | Guardia:' || :OLD.id_guardia;
      v_detalle := 'Antes -> Mat:' || :OLD.matricula_medico || ', Esp:' || :OLD.nombre_especialidad || ', Guardia:' || :OLD.id_guardia ||
                   ' | Despues -> Mat:' || :NEW.matricula_medico || ', Esp:' || :NEW.nombre_especialidad || ', Guardia:' || :NEW.id_guardia;
   ELSIF DELETING THEN
      v_op      := 'DELETE';
      v_clave   := 'Mat:' || :OLD.matricula_medico || ' | Esp:' || :OLD.nombre_especialidad || ' | Guardia:' || :OLD.id_guardia;
      v_detalle := 'Baja de asignacion de guardia.';
   END IF;

   INSERT INTO auditoria_guardias (usuario_bd, usuario_so, tabla_afectada, operacion, clave_registro, detalle_cambio)
   VALUES (USER, SYS_CONTEXT('USERENV', 'OS_USER'), 'DESEMPENA', v_op, v_clave, v_detalle);
END;
/

