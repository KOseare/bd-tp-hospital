CREATE TABLE sector (
   nombre_sector varchar2(100),
   constraint pk_sector primary key ( nombre_sector )
);

CREATE TABLE habitacion (
   nro_habitacion number(5),
   piso           number(3) not null,
   orientacion    varchar2(20) not null,
   nombre_sector  varchar2(100) not null,
   constraint pk_habitacion primary key ( nro_habitacion ),
   constraint fk_habitacion_sector foreign key ( nombre_sector )
      references sector ( nombre_sector )
);

-- Las camas se numeran desde 1 y pueden faltar numeros (cama 4 sin cama 3),
-- por eso el numero es un dato libre >= 1 y no una secuencia.
-- El estado libre/ocupada NO se guarda: se deriva (ver vistas, hipotesis 2.2).
CREATE TABLE cama (
   nro_habitacion number(5),
   nro_cama       number(3),
   constraint pk_cama primary key ( nro_habitacion,
                                    nro_cama ),
   constraint fk_cama_habitacion foreign key ( nro_habitacion )
      references habitacion ( nro_habitacion ),
   constraint ck_cama_nro check ( nro_cama >= 1 )
);

-- ---------- Personas, pacientes y medicos ----------
CREATE TABLE persona (
   dni      varchar2(9),
   nombre   varchar2(100) not null,
   apellido varchar2(100) not null,
   constraint pk_persona primary key ( dni ),
   constraint ck_persona_dni check ( regexp_like ( dni, '^[0-9]{6,9}$' ) )
);

CREATE TABLE paciente (
   dni                       varchar2(9),
   fecha_nacimiento_paciente date not null,
   sexo_paciente             char(1) not null,
   constraint pk_paciente primary key ( dni ),
   constraint fk_paciente_persona foreign key ( dni )
      references persona ( dni ),
   constraint ck_paciente_sexo
      check ( sexo_paciente in ( 'F', 'M', 'X' ) )
);

-- Claves candidatas: matricula (PK), dni y cuil_cuit (UNIQUE).
-- cantidad_guardias = maximo de guardias por mes que el medico acepta hacer.
-- foto queda nullable para poder dar de alta al medico antes de cargar la imagen.
CREATE TABLE medico (
   matricula_medico  number(10),
   dni               varchar2(9) not null,
   foto              blob,
   cuil_cuit         varchar2(11) not null,
   fecha_de_ingreso  timestamp with local time zone not null,
   cantidad_guardias number(3) default 0 not null,
   constraint pk_medico primary key ( matricula_medico ),
   constraint uq_medico_dni unique ( dni ),
   constraint uq_medico_cuil unique ( cuil_cuit ),
   constraint fk_medico_persona foreign key ( dni )
      references persona ( dni ),
   constraint ck_medico_cuil check ( regexp_like ( cuil_cuit,
                                                   '^[0-9]{11}$' ) ),
   constraint ck_medico_cant_guardias check ( cantidad_guardias >= 0 )
);

-- ---------- Internaciones y ocupacion de camas ----------
CREATE TABLE internacion (
   id_internacion                number(10) generated by default as identity,
   fecha_inicio_internacion      timestamp with local time zone not null,
   fecha_terminacion_internacion timestamp with local time zone,   -- NULL = en curso
   matricula_medico              number(10) not null,       -- medico principal
   dni                           varchar2(9) not null,       -- paciente internado
   constraint pk_internacion primary key ( id_internacion ),
   constraint fk_internacion_medico foreign key ( matricula_medico )
      references medico ( matricula_medico ),
   constraint fk_internacion_paciente foreign key ( dni )
      references paciente ( dni ),
   constraint ck_internacion_fechas check ( fecha_terminacion_internacion is null
       or fecha_terminacion_internacion > fecha_inicio_internacion )
);

-- PK = {id_internacion, fecha_asignacion_cama}: es la clave candidata MINIMA
-- (en una internacion el paciente esta en una sola cama a la vez, asi que la
-- cama no hace falta para identificar la fila; ver seccion de normalizacion).
CREATE TABLE ocupa (
   id_internacion         number(10),
   fecha_asignacion_cama  timestamp with local time zone,
   nro_habitacion         number(5) not null,
   nro_cama               number(3) not null,
   fecha_terminacion_cama timestamp with local time zone,          -- NULL = sigue en la cama
   constraint pk_ocupa primary key ( id_internacion,
                                     fecha_asignacion_cama ),
   constraint fk_ocupa_internacion foreign key ( id_internacion )
      references internacion ( id_internacion ),
   constraint fk_ocupa_cama
      foreign key ( nro_habitacion,
                    nro_cama )
         references cama ( nro_habitacion,
                           nro_cama ),
   constraint ck_ocupa_fechas check ( fecha_terminacion_cama is null
       or fecha_terminacion_cama > fecha_asignacion_cama )
);

-- ---------- Especialidades, guardias y vacaciones ----------
CREATE TABLE especialidad (
   nombre_especialidad varchar2(100),
   constraint pk_especialidad primary key ( nombre_especialidad )
);

CREATE TABLE posee (
   matricula_medico    number(10),
   nombre_especialidad varchar2(100),
   hace_guardia        char(1) default 'N' not null,
   constraint pk_posee primary key ( matricula_medico,
                                     nombre_especialidad ),
   constraint fk_posee_medico foreign key ( matricula_medico )
      references medico ( matricula_medico ),
   constraint fk_posee_especialidad foreign key ( nombre_especialidad )
      references especialidad ( nombre_especialidad ),
   constraint ck_posee_hace_guardia check ( hace_guardia in ( 'S', 'N' ) )
);

CREATE TABLE guardia (
   id_guardia           number(10) generated by default as identity,
   fecha_inicio_guardia timestamp with local time zone not null,
   fecha_fin_guardia    timestamp with local time zone not null,
   constraint pk_guardia primary key ( id_guardia ),
   constraint ck_guardia_fechas check ( fecha_fin_guardia > fecha_inicio_guardia )
);

-- La FK compuesta va contra POSEE: un medico solo cubre una guardia con una
-- especialidad que realmente tiene (y el trigger exige que haga_guardia = 'S').
CREATE TABLE desempena (
   matricula_medico    number(10),
   nombre_especialidad varchar2(100),
   id_guardia          number(10),
   constraint pk_desempena primary key ( matricula_medico,
                                         nombre_especialidad,
                                         id_guardia ),
   constraint fk_desempena_posee
      foreign key ( matricula_medico,
                    nombre_especialidad )
         references posee ( matricula_medico,
                            nombre_especialidad ),
   constraint fk_desempena_guardia foreign key ( id_guardia )
      references guardia ( id_guardia )
);

-- Una guardia puede abarcar uno o mas turnos (Manana = 1, Tarde = 2, Noche = 3)
CREATE TABLE guardia_turno_manana (
   id_guardia number(10),
   constraint pk_guardia_manana primary key ( id_guardia ),
   constraint fk_guardia_manana foreign key ( id_guardia )
      references guardia ( id_guardia )
);
CREATE TABLE guardia_turno_tarde (
   id_guardia number(10),
   constraint pk_guardia_tarde primary key ( id_guardia ),
   constraint fk_guardia_tarde foreign key ( id_guardia )
      references guardia ( id_guardia )
);
CREATE TABLE guardia_turno_noche (
   id_guardia number(10),
   constraint pk_guardia_noche primary key ( id_guardia ),
   constraint fk_guardia_noche foreign key ( id_guardia )
      references guardia ( id_guardia )
);

CREATE TABLE vacacion (
   matricula_medico number(10),
   fecha_inicio_vac timestamp with local time zone,
   fecha_fin_vac    timestamp with local time zone not null,
   constraint pk_vacacion primary key ( matricula_medico,
                                        fecha_inicio_vac ),
   constraint uq_vacacion_fin unique ( matricula_medico,
                                       fecha_fin_vac ),
   constraint fk_vacacion_medico foreign key ( matricula_medico )
      references medico ( matricula_medico ),
   constraint ck_vacacion_fechas check ( fecha_fin_vac > fecha_inicio_vac )
);

-- ---------- Rondas, recorridos y comentarios ----------
-- turno_ronda es un numero de turno.
CREATE TABLE ronda (
   id_ronda    number(10) generated by default as identity,
   dia_ronda   varchar2(10) not null,
   turno_ronda number(2) not null,
   constraint pk_ronda primary key ( id_ronda ),
   constraint ck_ronda_dia
      check ( dia_ronda in ( 'LUNES',
                             'MARTES',
                             'MIERCOLES',
                             'JUEVES',
                             'VIERNES',
                             'SABADO',
                             'DOMINGO' ) ),
   constraint ck_ronda_turno check ( turno_ronda >= 1 )
);

CREATE TABLE es_visitada (
   id_ronda       number(10),
   nro_habitacion number(5),
   constraint pk_es_visitada primary key ( id_ronda,
                                           nro_habitacion ),
   constraint fk_es_visitada_ronda foreign key ( id_ronda )
      references ronda ( id_ronda ),
   constraint fk_es_visitada_habitacion foreign key ( nro_habitacion )
      references habitacion ( nro_habitacion )
);

CREATE TABLE recorrido (
   id_recorrido     number(10) generated by default as identity,
   id_ronda         number(10) not null,
   matricula_medico number(10) not null,
   fecha_recorrido  timestamp with local time zone not null,
   constraint pk_recorrido primary key ( id_recorrido ),
   constraint fk_recorrido_ronda foreign key ( id_ronda )
      references ronda ( id_ronda ),
   constraint fk_recorrido_medico foreign key ( matricula_medico )
      references medico ( matricula_medico )
);

-- La fecha, el turno y el medico del comentario NO se repiten aca: se obtienen
-- de su recorrido (fecha y medico) y de la ronda del recorrido (turno).
CREATE TABLE comentario (
   id_comentario    number(10) generated by default as identity,
   id_internacion   number(10) not null,
   id_recorrido     number(10) not null,
   texto_comentario varchar2(2000) not null,
   constraint pk_comentario primary key ( id_comentario ),
   constraint fk_comentario_internacion foreign key ( id_internacion )
      references internacion ( id_internacion ),
   constraint fk_comentario_recorrido foreign key ( id_recorrido )
      references recorrido ( id_recorrido )
);